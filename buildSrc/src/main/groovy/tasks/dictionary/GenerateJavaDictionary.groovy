package tasks.dictionary

import extensions.AlfaExtension
import tasks.GitGuarded
import tasks.GitOutputGuard
import org.gradle.api.DefaultTask
import org.gradle.api.file.ProjectLayout
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.*
import org.yaml.snakeyaml.Yaml

import javax.inject.Inject

@CacheableTask
abstract class GenerateJavaDictionary extends DefaultTask implements GitGuarded {

    @Inject
    abstract ProjectLayout getLayout()

    @InputFile
    @PathSensitive(PathSensitivity.NONE)
    abstract RegularFileProperty getInputFile()

    @OutputFile
    abstract RegularFileProperty getOutputFile()

    // Tracked as @Input so a new commit correctly invalidates the up-to-date check / cache key —
    // both values end up embedded in the generated Dictionary.java javadoc.
    @Input
    abstract Property<String> getCommitRef()

    @Input
    abstract Property<String> getCommitDate()

    @Internal
    boolean allowUnsafe

    @Internal
    @Override
    File getGuardedOutputPath() { outputFile.get().asFile }

    @TaskAction
    void execute() {
        File out = outputFile.get().asFile
        GitOutputGuard.check(this, layout.projectDirectory.asFile, allowUnsafe, out)
        out.parentFile.mkdirs()

        String commitRefValue = commitRef.get()
        String commitDateValue = commitDate.get()

        def yaml = new Yaml()
        Map<String, Map> attributes = yaml.load(inputFile.get().asFile.newInputStream())

        List<Map> entries = attributes.collect { String key, Map attr ->
            String xacmlId = attr.xacmlId ?: key
            String constName = xacmlId.replaceAll('[^A-Za-z0-9]', '_').toUpperCase()
            [constName: constName, id: xacmlId, category: attr.category, datatype: attr.datatype]
        }.sort { it.constName }

        out.withWriter('UTF-8') { w ->
            w.writeLine('package apd;')
            w.writeLine('')
            w.writeLine('import java.util.Collections;')
            w.writeLine('import java.util.HashMap;')
            w.writeLine('import java.util.Map;')
            w.writeLine('')
            w.writeLine('/**')
            w.writeLine(' * Java implementation of Attribute Dictionary. Generated by Axiomatics Policy Devops.')
            w.writeLine(' * <p>')
            w.writeLine(" * Generated from commit ${commitRefValue} on ${commitDateValue}.")
            w.writeLine(' * <p>')
            w.writeLine(" * Do not edit manually — regenerate with: ./gradlew ${AlfaExtension.GENERATE_JAVA_DICTIONARY_TASK}")
            w.writeLine(' */')
            w.writeLine('public final class Dictionary {')
            w.writeLine('')
            w.writeLine('    public static final class Attribute {')
            w.writeLine('        public final String id;')
            w.writeLine('        public final String category;')
            w.writeLine('        public final String datatype;')
            w.writeLine('')
            w.writeLine('        public Attribute(String id, String category, String datatype) {')
            w.writeLine('            this.id = id;')
            w.writeLine('            this.category = category;')
            w.writeLine('            this.datatype = datatype;')
            w.writeLine('        }')
            w.writeLine('    }')
            w.writeLine('')

            entries.each { Map e ->
                w.writeLine("    public static final String ${e.constName} = \"${e.id}\";")
            }
            w.writeLine('')

            entries.each { Map e ->
                w.writeLine("    public static final Attribute ${e.constName}_ATTRIBUTE =")
                w.writeLine("        new Attribute(${e.constName}, \"${e.category}\", \"${e.datatype}\");")
            }
            w.writeLine('')

            w.writeLine('    private static final Map<String, Attribute> ATTRIBUTES;')
            w.writeLine('    static {')
            w.writeLine('        Map<String, Attribute> map = new HashMap<>();')
            entries.each { Map e ->
                w.writeLine("        map.put(${e.constName}, ${e.constName}_ATTRIBUTE);")
            }
            w.writeLine('        ATTRIBUTES = Collections.unmodifiableMap(map);')
            w.writeLine('    }')
            w.writeLine('')
            w.writeLine('    public static Map<String, Attribute> get() {')
            w.writeLine('        return ATTRIBUTES;')
            w.writeLine('    }')
            w.writeLine('')
            w.writeLine('    private Dictionary() {}')
            w.writeLine('}')
        }

        logger.lifecycle("GenerateJavaDictionary: wrote ${entries.size()} attribute(s) to ${out}")
    }
}
